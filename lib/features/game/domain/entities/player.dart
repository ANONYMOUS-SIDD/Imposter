// player.dart
//
// Immutable model for a single player in a game session.
//
// Lifecycle
// ---------
// Players are created in one of two phases:
//
//   Setup phase — a Player exists without a role. The setup screen adds,
//   removes, and reorders them. `Player.pending` is the preferred
//   constructor here because it documents intent at the call site.
//
//   Play phase — `GameEngine.assignRoles` produces a fresh list in which
//   every Player has a role of either civilian or imposter. Once assigned,
//   the role is fixed for the remainder of the session; only `hasRevealed`
//   changes as the reveal sequence advances.
//
// A session is only valid for play when every player in its list has a
// role. `hasRole` exists so callers can assert that invariant cheaply.
//
// Equality
// --------
// Two Player instances are equal only when their id, name, role, and
// hasRevealed fields all match. Comparing the full state instead of just
// the id means `copyWith(hasRevealed: true)` produces a value that is not
// equal to the original — which is exactly what Riverpod change detection
// needs to rebuild the reveal screen when a player has advanced.
//
// The consequence is that `Set<Player>` de-duplicates only by
// fully-identical instances. That is acceptable because the engine and
// the session model operate on ordered `List<Player>` collections, never
// on sets.
//
// Immutability
// ------------
// All fields are `final`; state changes go through `copyWith` and return
// a new instance. `copyWith` deliberately omits `id` and `name`: the id
// is the player's identity, and the name does not change mid-session.
// Allowing either to be changed would open the door to duplicate-id and
// identity-split bugs; renaming a player, if ever needed, is a
// session-level operation rather than a per-player one.

import 'package:flutter/foundation.dart';

/// Role assigned to a player for a single round.
///
/// Nullable during setup, non-null during play. Use [Player.hasRole] to
/// check without null-dereferencing.
enum PlayerRole { civilian, imposter }

@immutable
class Player {
  const Player({
    required this.id,
    required this.name,
    this.role,
    this.hasRevealed = false,
  })  : assert(id != '', 'Player.id must not be empty'),
        assert(name != '', 'Player.name must not be empty');

  /// Constructs a player in the setup phase, before any role has been
  /// assigned.
  ///
  /// Equivalent to the default constructor without a role, but documents
  /// the intent at the call site: the player is pending role assignment.
  const Player.pending({
    required this.id,
    required this.name,
  })  : role = null,
        hasRevealed = false,
        assert(id != '', 'Player.id must not be empty'),
        assert(name != '', 'Player.name must not be empty');

  /// Stable identifier for the player. Used as a widget key and for
  /// reveal-state lookups. Generated by `GameEngine.assignRoles`.
  final String id;

  /// Display name. Never empty. Uniqueness within a session is enforced by
  /// the setup screen, not by this model.
  final String name;

  /// Role assigned to this player. `null` before a round has been created,
  /// and either [PlayerRole.civilian] or [PlayerRole.imposter] afterward.
  ///
  /// A role is never unset once assigned — the rules and reveal sequence
  /// assume it is fixed for the session's lifetime.
  final PlayerRole? role;

  /// Whether the player has already viewed their secret in the reveal
  /// sequence. The reveal screen uses this to advance to the next player.
  final bool hasRevealed;

  /// `true` once [role] has been assigned.
  bool get hasRole => role != null;

  /// `true` only when this player is an imposter. Returns `false` when
  /// [role] is null, so it is safe to call during setup.
  bool get isImposter => role == PlayerRole.imposter;

  /// `true` only when this player is a civilian. Returns `false` when
  /// [role] is null.
  bool get isCivilian => role == PlayerRole.civilian;

  /// Returns a copy with the given fields replaced.
  ///
  /// [id] and [name] are intentionally not settable — see the file header
  /// for reasoning.
  Player copyWith({
    PlayerRole? role,
    bool? hasRevealed,
  }) =>
      Player(
        id: id,
        name: name,
        role: role ?? this.role,
        hasRevealed: hasRevealed ?? this.hasRevealed,
      );

  /// Content equality across all four fields. See the file header for why
  /// the id alone is not sufficient.
  @override
  bool operator ==(Object other) =>
      identical(this, other) ||
          other is Player &&
              other.id == id &&
              other.name == name &&
              other.role == role &&
              other.hasRevealed == hasRevealed;

  /// Hash consistent with [==].
  @override
  int get hashCode => Object.hash(id, name, role, hasRevealed);

  @override
  String toString() =>
      'Player(id: $id, name: $name, '
          'role: ${role?.name ?? 'pending'}, revealed: $hasRevealed)';
}